    // 아이디로 안내 찾기 (없으면 null). 자바의 map.get(id)
    public static TutorialTip Find(string id)
    {
        foreach (TutorialTip t in Tips) if (t.Id == id) return t;
        return null;
    }

    // 전부의 아이디 (다시 보기 초기화용)
    public static List<string> AllIds()
    {
        List<string> ids = new List<string>();
        foreach (TutorialTip t in Tips) ids.Add(t.Id);
        return ids;
    }
